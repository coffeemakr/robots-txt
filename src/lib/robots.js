// robots.txt parsing, evaluation and generation. No DOM: the components render the results.
import {data, POLICY, GEN_CATS, companyOrder, inCat, inGenCat, isEngine, tableBots} from './catalog.js';

const GOOGLE_FALLBACK = {'googlebot-image': ['Googlebot'], 'googlebot-video': ['Googlebot'], 'googlebot-news': ['Googlebot']};
const UA_KEYS = ['user-agent', 'useragent', 'user agent'];
const DIS_KEYS = ['disallow', 'dissallow', 'dissalow', 'disalow', 'diasllow', 'disallaw'];
const NOT_DIRECTIVES = ['noindex', 'nofollow', 'noarchive', 'noai', 'noimageai'];
const SILENT_KEYS = ['host', 'request-rate', 'visit-time', 'clean-param'];
// Stands in for "any characters" in probe paths; a private-use character no real path contains
const SENTINEL = '\uE000';

export const GEN_HEAD = '# robots.txt generated by robots.txt AI check';
// Title of the generated group that lets bots in on purpose, so readBlock can tell it from the automatic ones
const ALLOW_TITLE = 'Allowed on purpose';

// Product token, the way crawlers compare names: "PerplexityBot/1.0" → "perplexitybot"
function norm(ua) {
  const t = String(ua).trim();
  if (t === '*') return '*';
  const m = t.match(/^[A-Za-z_-]+/);
  return (m ? m[0] : t).toLowerCase();
}

// Name up to the first slash or space, for looking up this tool's notes
const full = (ua) => String(ua).trim().split(/[\/\s]/)[0].toLowerCase();
// The user-agent table's entries by their user-agent's name; the keys in the data are only IDs
const EXTRA_NOTES = new Map(Object.values(data.userAgentNotes).map(n => [full(n.ua), n]));

export function parseRobots(text) {
  const groups = [], warnings = [], signals = [], sitemaps = [];
  let cur = null, lastUA = false;
  const warn = (i, raw, msg) => warnings.push({line: i + 1, text: raw.trim().slice(0, 200), msg});
  String(text).replace(/^﻿/, '').split(/\r\n|\r|\n/).forEach((raw, i) => {
    const line = raw.replace(/#.*$/, '').trim();
    if (!line) return;
    let key, val, m = line.match(/^([A-Za-z][A-Za-z _-]*?)\s*:\s*(.*)$/);
    if (m) {key = m[1].toLowerCase().replace(/\s+/g, ' '); val = m[2].trim();}
    else if ((m = line.match(/^(allow|disallow|user-agent)\s+(\S.*)$/i))) {
      key = m[1].toLowerCase(); val = m[2].trim();
      warn(i, raw, 'Missing colon. Google accepts this; other crawlers may not');
    } else {warn(i, raw, 'Not a “field: value” line, ignored'); return;}

    if (UA_KEYS.includes(key)) {
      if (key !== 'user-agent') warn(i, raw, `“${m[1]}” is a misspelling of User-agent. Google accepts it; other crawlers may not`);
      if (!cur || !lastUA) {cur = {agents: [], rules: [], line: i + 1}; groups.push(cur);}
      if (val) cur.agents.push(val); else warn(i, raw, 'Empty User-agent line');
      lastUA = true;
      return;
    }
    if (key === 'allow' || DIS_KEYS.includes(key)) {
      const type = key === 'allow' ? 'allow' : 'disallow';
      if (type === 'disallow' && key !== 'disallow') warn(i, raw, `“${m[1]}” is a misspelling of Disallow. Google accepts it; other crawlers may not`);
      lastUA = false;
      if (!cur) {warn(i, raw, 'Rule before any User-agent line, ignored by crawlers'); return;}
      const rule = {type, path: val, line: i + 1};
      if (val && !val.startsWith('/') && !val.startsWith('*')) {rule.ignored = true; warn(i, raw, 'Path doesn’t start with / so it matches nothing (Google ignores it)');}
      cur.rules.push(rule);
      return;
    }
    if (key === 'content-signal' || key === 'content-usage') signals.push({key: m[1], val, line: i + 1, agents: cur ? cur.agents.slice() : []});
    else if (key === 'sitemap' || key === 'site-map') sitemaps.push(val);
    else if (key === 'crawl-delay') {if (cur) cur.crawlDelay = val;}
    else if (NOT_DIRECTIVES.includes(key)) warn(i, raw, `“${m[1]}” isn’t a robots.txt directive; crawlers ignore it`);
    else if (!SILENT_KEYS.includes(key)) warn(i, raw, `Unknown field “${m[1]}”, ignored`);
  });
  return {groups, warnings, signals, sitemaps};
}

// Every group naming this user-agent (crawlers merge them)
const groupsNaming = (parsed, ua) => parsed.groups.filter(g => g.agents.some(a => norm(a) === norm(ua)));

// The rules a bot follows: its own groups, else its documented fallback's, else the * group.
export function rulesFor(ua, parsed, fallback) {
  const fb = fallback && fallback.length ? fallback : (GOOGLE_FALLBACK[norm(ua)] || []);
  for (const t of [ua, ...fb, '*']) {
    const gs = groupsNaming(parsed, t);
    if (gs.length) return {rules: gs.flatMap(g => g.rules), via: t, named: t === ua};
  }
  return {rules: [], via: null, named: false};
}

// Linear-time wildcard match in the style of Google's robots.txt parser:
// tracks every position in the path the pattern could have reached.
export function matches(path, pat) {
  const n = path.length, m = pat.length;
  let pos = [0];
  for (let j = 0; j < m; j++) {
    const c = pat[j];
    if (c === '$' && j === m - 1) return pos[pos.length - 1] === n;
    if (c === '*') {
      const from = pos[0]; pos = [];
      for (let k = from; k <= n; k++) pos.push(k);
    } else {
      const next = [];
      for (const p of pos) if (p < n && path[p] === c) next.push(p + 1);
      if (!next.length) return false;
      pos = next;
    }
  }
  return true;
}

// Rules that have any effect: empty and malformed paths match nothing
const liveRules = (rules) => rules.filter(r => r.path && !r.ignored);

// Longest match wins; on a tie, Allow wins.
export function allowed(path, rules) {
  let best = null;
  for (const r of liveRules(rules)) {
    if (!matches(path, r.path)) continue;
    const len = r.path.length;
    if (!best || len > best.len || (len === best.len && r.type === 'allow')) best = {len, type: r.type};
  }
  return best ? best.type === 'allow' : true;
}

// Whether rules block a bot from everything, nothing or some paths, by probing typical paths and each rule's own.
const evalCache = new Map();
export function evaluate(rules) {
  const live = liveRules(rules);
  const key = live.map(r => r.type[0] + r.path).join('\n');
  if (evalCache.has(key)) return evalCache.get(key);
  let out;
  if (!live.length) out = {status: 'allowed', blocked: [], open: []};
  else {
    const S = SENTINEL;
    const probes = new Set(['/', '/index.html', '/a/b/page.html', '/page?x=1', '/' + S, '/img/photo.jpg', '/doc.pdf']);
    for (const r of live) {
      if (probes.size > 4000) break;
      let raw = r.path.replace(/\$$/, '');
      if (!raw.startsWith('/')) raw = '/' + raw;
      const lit = raw.replace(/\*/g, S), stem = raw.split('*')[0];
      for (const s of [lit, stem]) {probes.add(s); if (!r.path.endsWith('$')) probes.add(s + S);}
    }
    let yes = 0, no = 0;
    for (const p of probes) {if (allowed(p, live)) yes++; else no++; if (yes && no) break;}
    const status = !no ? 'allowed' : !yes ? 'blocked' : 'partial';
    out = {
      status,
      mostly: status === 'partial' && !allowed('/' + S + '/' + S, live),
      blocked: live.filter(r => r.type === 'disallow').map(r => r.path),
      open: live.filter(r => r.type === 'allow').map(r => r.path),
    };
  }
  if (evalCache.size > 500) evalCache.clear();
  evalCache.set(key, out);
  return out;
}

// A catalog bot's purposes, in the words of the company table's columns. The regular search engines are search
// bots there, but named as what they are here.
const PURPOSE = [['train', 'training'], ['search', 'AI search'], ['fetch', 'user-requested fetch']];
const purposes = (b) => isEngine(b) ? 'search engine' : PURPOSE.filter(([c]) => inCat(b, c)).map(([, l]) => l).join(' · ');

// companies: the catalog with each bot's result. named: every user-agent the file names, with a note on what it is
// and, for the catalog's bots, a tag with its purposes.
export function analyze(text) {
  const parsed = parseRobots(text);
  const known = new Map();
  const companies = [...data.companies].sort(companyOrder).map(c => ({
    name: c.name, open: c.open, major: !!c.major, share: c.share, trainNote: c.trainNote, notes: c.notes, link: c.link,
    bots: c.bots.map(b => {
      if (!b.label) known.set(full(b.ua), b);
      const r = rulesFor(b.ua, parsed, b.fallback);
      return {...b, ...evaluate(r.rules), via: r.via, named: r.named};
    }),
  }));
  const named = [];
  const seen = new Set();
  for (const g of parsed.groups) for (const a of g.agents) {
    const n = norm(a);
    if (seen.has(n)) continue;
    seen.add(n);
    const ev = evaluate(rulesFor(a, parsed).rules);
    const k = known.get(full(a)), x = EXTRA_NOTES.get(full(a));
    let kind = 'unknown', note = 'Not in this tool’s list. Check the operator’s documentation', tag;
    if (k) {
      kind = k.ignores ? 'ignores' : k.caution ? 'caution' : 'documented';
      note = k.ignores || k.caution || k.note || '';
      tag = purposes(k);
    } else if (x) {kind = x.kind; note = x.note;}
    named.push({ua: a, ...ev, kind, note, tag, src: k ? k.src : undefined, url: !k && x ? x.url : undefined});
  }
  return {parsed, companies, named};
}

// The groups that block the bots in sel (a Set of user-agent strings) from the whole site, and let the bots in allow
// in everywhere, each followed by a blank line. own: the parsed file the groups are added to, if any. Bots it names
// keep their own rules, and a bot that would inherit a blocked bot's rules gets that bot's rules from own instead
// of Allow: /.
function groupLines(sel, own, allow = new Set()) {
  const bots = [...data.companies.flatMap(c => c.bots), ...tableBots];
  const out = [], seen = new Set();
  const group = (title, uas, rules, comments = []) => {
    const list = uas.filter(u => !seen.has(u.toLowerCase())).sort((x, y) => x.localeCompare(y, 'en', {sensitivity: 'base'}));
    if (!list.length) return;
    list.forEach(u => seen.add(u.toLowerCase()));
    out.push(`# ${title}`, ...comments.map(c => `# ${c}`), ...list.map(u => `User-agent: ${u}`), ...rules, '');
  };
  // A bot in several sections (Bytespider) goes in the one with the largest share of its bots blocked, so it
  // shows up under what was picked
  const share = Object.fromEntries(GEN_CATS.map(([c]) => {
    const bs = bots.filter(b => inGenCat(b, c));
    return [c, bs.length ? bs.filter(b => sel.has(b.ua)).length / bs.length : 0];
  }));
  const home = (b) => GEN_CATS.map(([c]) => c).filter(c => inGenCat(b, c)).reduce((x, y) => share[y] > share[x] ? y : x);
  for (const [cat, title] of GEN_CATS) {
    const picked = bots.filter(b => sel.has(b.ua) && inGenCat(b, cat) && home(b) === cat);
    const comments = [];
    if (cat === 'train' && sel.has(POLICY)) comments.push('__usage_ai-training: shared training opt-out (Anthropic now, Google and Microsoft from early 2027)');
    if (cat === 'engines' && sel.has('Googlebot')) comments.push('Blocking Googlebot removes this site from Google Search entirely');
    if (cat === 'engines' && sel.has('Bingbot')) comments.push('Blocking Bingbot removes this site from Bing and Copilot answers');
    if (cat === 'fetch' && picked.some(b => b.ignores)) comments.push('Some of these say they may ignore robots.txt for user requests');
    if (cat === 'seo' && picked.length) comments.push('Includes audit tools you may run on your own site, such as Screaming Frog and Sitebulb');
    group(title, picked.map(b => b.ua), ['Disallow: /'], comments);
  }
  group(ALLOW_TITLE, bots.filter(b => allow.has(b.ua) && !sel.has(b.ua)).map(b => b.ua), ['Allow: /'],
    ['Let in everywhere, whatever the rest of this file says']);
  // Unselected bots that would otherwise inherit a blocked bot's rules (documented fallbacks)
  const ownGroups = (ua) => own ? groupsNaming(own, ua) : [];
  const from = (b) => b.fallback.find(f => sel.has(f));
  const kept = (b) => liveRules(ownGroups(from(b)).flatMap(g => g.rules));
  const inherit = bots.filter(b => !b.label && !sel.has(b.ua) && !allow.has(b.ua) && !ownGroups(b.ua).length && (b.fallback || []).some(f => sel.has(f)));
  const plain = inherit.filter(b => !kept(b).length).sort((x, y) => x.ua.localeCompare(y.ua, 'en', {sensitivity: 'base'}));
  group("Allowed explicitly, so they don't inherit the rules above", plain.map(b => b.ua), ['Allow: /'],
    plain.map(b => `${b.ua} would otherwise follow the ${from(b)} group`));
  for (const b of inherit.filter(b => kept(b).length))
    group(`${b.ua} keeps this file's ${from(b)} rules, so it doesn't inherit the block above`, [b.ua],
      kept(b).map(r => `${r.type === 'allow' ? 'Allow' : 'Disallow'}: ${r.path}`));
  return out;
}

// A whole file. sel: Set of user-agent strings to block from the whole site.
// opts: { signal: Content-Signal value for the * group, date: 'YYYY-MM-DD', allow: Set of user-agents to let in }
export function generate(sel, opts = {}) {
  return [`${GEN_HEAD}${opts.date ? ' on ' + opts.date : ''}`,
    sel.size ? '# Blocks the bots listed below from the whole site. Everything else stays allowed.'
      : '# Blocks nothing: every bot is allowed everywhere.', '',
    ...groupLines(sel, null, opts.allow),
    '# Everyone else', 'User-agent: *', ...(opts.signal ? [`Content-Signal: ${opts.signal}`] : []), 'Allow: /',
  ].join('\n') + '\n';
}

// Adding to a file the user already has: the generated groups go between BEGIN and END comments, and the rest of
// the file is left alone. Regenerating replaces that block in place; selecting nothing removes it.
const BLOCK_RE = /^# BEGIN robots\.txt AI check\b[^\n]*\n(?:(?!# BEGIN robots\.txt AI check\b)[^\n]*\n)*?# END robots\.txt AI check\b[^\n]*(?:\n|$)/m;
export const hasBlock = (text) => BLOCK_RE.test(text);

// opts: { date: 'YYYY-MM-DD', allow: Set of user-agents to let in }
export function mergeBlock(text, sel, opts = {}) {
  text = String(text).replace(/\r\n?/g, '\n');
  const m = text.match(BLOCK_RE);
  const before = m ? text.slice(0, m.index) : text, after = m ? text.slice(m.index + m[0].length) : '';
  const body = groupLines(sel, parseRobots(before + after), opts.allow);
  while (body.length && !body[body.length - 1]) body.pop();
  if (!body.length) return m ? before + after.replace(/^\n/, '') : text;
  const block = [`# BEGIN robots.txt AI check${opts.date ? ', generated on ' + opts.date : ''}. Lines up to END are replaced when it's regenerated.`,
    '# Blocks the bots below from the whole site, or lets them in where noted. The rest of this file is unchanged.', '',
    ...body, '# END robots.txt AI check'].join('\n') + '\n';
  if (m) return before + block + after;
  // Above the first group, so it can't run into one (a group's User-agent lines continue until its first rule),
  // and below any header comments
  const at = text.search(/^[ \t]*user[ _-]?agent[ \t]*:/im);
  if (at >= 0) return text.slice(0, at) + block + '\n' + text.slice(at);
  return text.trim() ? text.replace(/\s*$/, '\n\n') + block : block;
}

// What the generated part of text (the marked block, or the whole file if this tool generated it) blocks and lets
// in: { block, allow }, Sets of the catalog's user-agent strings. Groups added only so bots don't inherit a block
// are left out: they follow from the rest.
export function readBlock(text) {
  text = String(text).replace(/\r\n?/g, '\n');
  const m = text.match(BLOCK_RE);
  const part = m ? m[0] : text.trimStart().startsWith(GEN_HEAD) ? text : '';
  const known = new Map([...data.companies.flatMap(c => c.bots), ...tableBots].map(b => [b.ua.toLowerCase(), b.ua]));
  const block = new Set(), allow = new Set();
  for (const para of part.split(/\n[ \t]*\n/)) {
    const lines = para.split('\n').map(l => l.trim()).filter(Boolean);
    const uas = lines.map(l => l.match(/^user-agent\s*:\s*(.+)$/i)).filter(Boolean).map(x => known.get(x[1].trim().toLowerCase()));
    const rules = lines.filter(l => !l.startsWith('#') && !/^user-agent\s*:/i.test(l));
    const to = rules.length === 1 && /^disallow\s*:\s*\/$/i.test(rules[0]) ? block : lines[0] === '# ' + ALLOW_TITLE ? allow : null;
    if (to) uas.filter(Boolean).forEach(u => to.add(u));
  }
  return {block, allow};
}
